const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const api=require('../plant-photos');
assert.equal(api.scope('',''),'guest');
assert.equal(api.scope('A',''),'user:A');
assert.equal(api.scope('A','A'),'user:A');
assert.equal(api.scope('B','A'),null);
assert.equal(api.scope('','A'),null);
assert.notEqual(api.key('guest','plot_1'),api.key('user:A','plot_1'));
assert.notEqual(api.key('user:A','plot_1'),api.key('user:B','plot_1'));
for(const owner of [null,'','user:','user:a|b','guest|plot','__proto__'])assert.throws(()=>api.key(owner,'plot_1'));
for(const id of ['',null,'x|y','../../x','<img>','a'.repeat(101)])assert.throws(()=>api.key('guest',id));
for(const type of ['image/jpeg','image/png','image/webp'])assert.doesNotThrow(()=>api.validateFile({type,size:100}));
for(const file of [null,{type:'image/svg+xml',size:100},{type:'image/heic',size:100},{type:'image/jpeg',size:0},{type:'image/jpeg',size:api.MAX_INPUT+1}])assert.throws(()=>api.validateFile(file));
assert.equal(api.signature(Uint8Array.from([255,216,255]),'image/jpeg'),true);
assert.equal(api.signature(new TextEncoder().encode('<svg>'),'image/jpeg'),false);
assert.equal(api.signature(Uint8Array.from([137,80,78,71,13,10,26,10]),'image/png'),true);
assert.equal(api.signature(new TextEncoder().encode('RIFFxxxxWEBP'),'image/webp'),true);
const root=path.resolve(__dirname,'..');
for(const file of ['balcony.js','balcony.css','plant-photos.js'])for(const list of ['index.html','sw.js','scripts/build-release.mjs','scripts/check-release.mjs'])assert.ok(fs.readFileSync(path.join(root,list),'utf8').includes(file),list+' packages '+file);
const photoSource=fs.readFileSync(path.join(root,'plant-photos.js'),'utf8');
assert.doesNotMatch(photoSource,/fetch\(|XMLHttpRequest|firebase|localStorage\.setItem|readAsDataURL/);
assert.match(fs.readFileSync(path.join(root,'privacy.html'),'utf8'),/照片不會傳送至雲端或 OCR/);
assert.match(fs.readFileSync(path.join(root,'balcony.js'),'utf8'),/照片只存這個瀏覽器/);
console.log('Plant photos: isolated ownership, format/size/signature guards, no network storage, privacy and packaging passed');
