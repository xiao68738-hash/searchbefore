const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const mode = require('../experience-mode');
for (const name of ['simple','standard','complete']) assert.equal(mode.normalize(name), name);
for (const name of [null,undefined,'','expert','__proto__','constructor']) assert.equal(mode.normalize(name),'standard');
const memory = new Map();
const storage = () => ({getItem:k=>memory.get(k),setItem:(k,v)=>memory.set(k,v)});
assert.equal(mode.read(storage),'standard');
assert.equal(mode.write(storage,'simple'),true);
assert.equal(mode.read(storage),'simple');
const unavailable = () => {throw new Error('blocked');};
assert.equal(mode.read(unavailable),'standard');
assert.equal(mode.write(unavailable,'complete'),false);
assert.equal(memory.size,1);
const root = path.resolve(__dirname,'..');
const index = fs.readFileSync(path.join(root,'index.html'),'utf8');
assert.ok(index.includes('id="experienceMode"'));
assert.ok(index.includes('./experience-mode.js'));
assert.ok(index.includes('./guide-query.html'));
for(const file of ['experience-mode.js','guide-query.html']) {
  assert.ok(fs.readFileSync(path.join(root,'sw.js'),'utf8').includes(file));
  assert.ok(fs.readFileSync(path.join(root,'scripts/build-release.mjs'),'utf8').includes(file));
  assert.ok(fs.readFileSync(path.join(root,'scripts/check-release.mjs'),'utf8').includes(file));
}
console.log('experience mode: defaults, preferences, storage failure and packaging passed');
const guide=fs.readFileSync(path.join(root,'guide-query.html'),'utf8');
assert.ok(guide.includes('rel="canonical" href="https://searchbefore.tw/guide-query.html"'));
assert.ok(guide.includes('2026-10-23'));
assert.ok(guide.includes('配方與顯示偏好不在這份同步清單內'));
for(const link of guide.matchAll(/href="\.\/([^"#?]+)"/g)) assert.ok(fs.existsSync(path.join(root,link[1])));
assert.ok(fs.readFileSync(path.join(root,'sitemap.xml'),'utf8').includes('https://searchbefore.tw/guide-query.html'));
console.log('query tutorial: canonical, dates, scope and local links passed');
const entry = index.match(/<p class="entry-note">[\s\S]*?<\/p>/)[0];
assert.ok(entry.includes('./guides.html'));
assert.ok(entry.includes('./guide-query.html'));
const hub=fs.readFileSync(path.join(root,'guides.html'),'utf8');
assert.ok(hub.includes('id="reading-order"'));
assert.ok(hub.includes('id="content-method"'));
assert.ok(fs.readFileSync(path.join(root,'about.html'),'utf8').includes('id="content-feedback"'));
assert.ok(!fs.readFileSync(path.join(root,'about.html'),'utf8').includes('不登入也能使用目前所有功能'));
console.log('public learning access: before-login links, reading order and corrections passed');
